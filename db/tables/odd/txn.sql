CREATE TABLE IF NOT EXISTS odd.txn (
  txn_id       bigint GENERATED BY DEFAULT AS IDENTITY,
  insert_dt    timestamp not null default now(),
  bettor_id    bigint not NULL,
  syndicate_id bigint not NULL,
  bet_hash     varchar(32),
  parlay_id    bigint,
  unit         float,
  price        float,
  won          boolean,
  won_ts       timestamp,
  canceled     boolean default (false),
  cancel_ts    timestamp,

  CONSTRAINT chk_bet_or_parlay CHECK (bet_hash IS NOT NULL OR parlay_id IS NOT NULL)
);
